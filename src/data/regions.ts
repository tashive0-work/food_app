/** 위도·경도로 가장 가까운 지역을 추정합니다 (정확한 행정구역 판정이 아닙니다). */
export function guessRegion(lat: number, lng: number): Region {
  let best = REGIONS[0];
  let bestD = Infinity;
  for (const r of REGIONS) {
    const d = (r.lat - lat) ** 2 + (r.lng - lng) ** 2;
    if (d < bestD) { bestD = d; best = r; }
  }
  return best;
}
