/**
 * 특정 음식에 대한 1초 결정 가이드 반환.
 * 개별 사전에 없으면 음식 카테고리/속성 기반의 스마트 가이드를 자동 생성하여 반환합니다.
 */
export function getFoodGuide(foodName: string, kind?: string, spice?: number, warm?: number): FoodGuide {
  if (FOOD_GUIDES[foodName]) {
    return FOOD_GUIDES[foodName];
  }

  // 자동 생성 스마트 가이드
  const isSpicy = (spice ?? 0) >= 3;
  const isWarm = (warm ?? 0) >= 3;
  const k = kind || "음식";

  let bestWhen = `기분 좋은 한 끼로 든든하게 에너지를 충전하고 싶을 때 추천하는 ${k} 메뉴예요.`;
  if (isSpicy) {
    bestWhen = `칼칼하고 화끈한 맛으로 묵은 스트레스를 시원하게 날리고 싶을 때 딱이에요!`;
  } else if (isWarm) {
    bestWhen = `속을 훈훈하고 편안하게 달래주는 따뜻한 온기가 필요할 때 추천드려요.`;
  }

  let pairing = "시원한 음료 또는 아삭한 샐러드·김치";
  if (k === "한식") pairing = "정갈한 밑반찬 + 갓 지은 흰쌀밥";
  else if (k === "일식") pairing = "따뜻한 미소장국 + 락교/초생강";
  else if (k === "중식") pairing = "단무지와 양파 + 자스민차";
  else if (k === "양식") pairing = "신선한 피클 + 시원한 탄산수";
  else if (k === "분식") pairing = "바삭한 튀김 + 시원한 탄산음료";
  else if (k === "야식") pairing = "시원한 보리차 또는 무알콜 맥주";

  return {
    bestWhen,
    pairing,
    tip: "식사 전 물 한 모금으로 입안을 깔끔하게 정돈하고 맛을 음미해 보세요.",
  };
}
